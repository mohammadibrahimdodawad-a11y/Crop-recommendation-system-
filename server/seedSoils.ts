export function seedSoils(): void {
  const existingCount = (db.prepare('SELECT COUNT(*) AS cnt FROM soil_types').get() as { cnt: number }).cnt;
  if (existingCount === 0) {
    const insertSoil = db.prepare(`
      INSERT INTO soil_types (
        wrb_code, wrb_name, usda_equivalent, regional_names,
        simple_explanation, simple_explanation_kn, typical_ph_min, typical_ph_max,
        drainage_class, fertility_notes, global_occurrence, source_reference
      ) VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?)
    `);

    for (const s of WRB_SOILS) {
      insertSoil.run(
        s.wrb_code,
        s.wrb_name,
        s.usda_equivalent,
        s.regional_names,
        s.simple_explanation,
        s.simple_explanation_kn,
        s.typical_ph_min,
        s.typical_ph_max,
        s.drainage_class,
        s.fertility_notes,
        s.global_occurrence,
        s.source_reference,
      );
    }
  }

  const texCount = (db.prepare('SELECT COUNT(*) AS cnt FROM soil_textures').get() as { cnt: number }).cnt;
  if (texCount === 0) {
    const insertTex = db.prepare(`
      INSERT INTO soil_textures (
        name, name_kn, sand_pct_range, silt_pct_range, clay_pct_range,
        water_retention, drainage_rate, workability_notes
      ) VALUES (?, ?, ?, ?, ?, ?, ?, ?)
    `);
    for (const t of SOIL_TEXTURES) {
      insertTex.run(
        t.name,
        t.name_kn,
        t.sand_pct_range,
        t.silt_pct_range,
        t.clay_pct_range,
        t.water_retention,
        t.drainage_rate,
        t.workability_notes,
      );
    }
  }
}
